/// @brief コンストラクタ
/// @param display 
AppPlaycardSprites::AppPlaycardSprites(AppDisplay *display)
{
    _Display = display;
}


/// @brief 初期化
void AppPlaycardSprites::init()
{
    // 空白カード部分
    {
        auto sprite = _Display->createSprite(16, 32);
        sprite->setFont(&fonts::Font2);
        sprite->fillRect(0, 0, 16, 32, TFT_BLACK);
        _Sprites_Collection[0] = sprite;
    }    

    // カード部分
    for(int index=1; index<__ARRAY_SIZE__(_Sprites_Collection); ++index)
    {
        const uint16_t *suit_bitmap[] = {bitmap_suit_s, bitmap_suit_h, bitmap_suit_d, bitmap_suit_c,};
        const uint16_t suit_color[] ={TFT_WHITE, TFT_RED, TFT_CYAN, TFT_GREEN};
        const char *rank_text[] = {"A","2","3","4","5","6","7","8","9","T","J","Q","K"};

        int card_number = index - 1;
        int suit = card_number / 13;
        int rank = card_number % 13;

        auto sprite = _Display->createSprite(16, 32);
        sprite->setFont(&fonts::Font2);
        sprite->pushImage(5, 3, 8, 8, suit_bitmap[suit]);
        sprite->setTextColor(suit_color[suit]);
        sprite->drawString(rank_text[rank], 5, 15);
        sprite->drawRect(0, 0, 16, 32, suit_color[suit]);
        _Sprites_Collection[index] = sprite;
    }
}


/// @brief 描画
/// @param index カードインデックス(As:1 ～ Kc:52)
/// @param x 
/// @param y 
void AppPlaycardSprites::draw(int index, int x, int y)
{
    if(index >= 0 && index < __ARRAY_SIZE__(_Sprites_Collection))
    {
        _Sprites_Collection[index]->pushSprite( x, y );
    }
}
