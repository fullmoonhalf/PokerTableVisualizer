static const uint16_t *suit_bitmap[] = {bitmap_suit_s, bitmap_suit_h, bitmap_suit_d, bitmap_suit_c,};
static const uint16_t suit_color[] ={TFT_WHITE, TFT_RED, TFT_CYAN, TFT_GREEN};
static const char *rank_text[] = {"A","2","3","4","5","6","7","8","9","T","J","Q","K"};


/// @brief コンストラクタ
/// @param index 
SysSprite *createPlaycardSprite(int index)
{
    int suit = (index - 1) / 13;
    int rank = (index - 1) % 13;

    auto _Sprite = SysSpriteManager::getInstance().createSprite(16, 32);
    _Sprite->clear();
    _Sprite->drawImage(5, 3, 8, 8, suit_bitmap[suit]);
    _Sprite->drawText(5, 18, 1.0f, suit_color[suit], rank_text[rank]);
    _Sprite->drawRect(0, 0, 16, 32, suit_color[suit]);

    return _Sprite;
}
